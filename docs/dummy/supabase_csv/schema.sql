-- 상품 DB 스키마 (실습 전용 · 가상 상품 데이터)
-- 기준 문서: docs/dummy/supabase_csv/schema.md
-- 실행: Supabase 대시보드 → SQL Editor에 붙여 넣고 Run
-- 데이터: 실행 후 Table Editor → Import data from CSV로 같은 폴더의 CSV를 가져온다
--         순서: products → product_storage, product_cautions → shipping_policy
--         id 컬럼은 CSV에 없으니 매핑하지 않는다 (자동 생성)

-- ─────────────────────────────────────────────
-- 상품 (products.csv, 10행)
-- ─────────────────────────────────────────────
create table public.products (
  product_id    text primary key,                 -- 예: P-0113
  product_name  text not null,
  category      text,                             -- 가안 값, 기준 확정 전이라 check 없음
  origin        text,                             -- 모르면 '미확인'
  ingredients   text,
  spec          text,                             -- 단위가 제각각이라 텍스트
  price         integer not null check (price >= 0),  -- 원 단위
  sale_period   text,                             -- 계절 상품만 (예: 4~7월)
  description   text,
  allergens     text,                             -- 상품에 직접 들어 있는 성분
  cross_contact text                              -- 생산 라인을 함께 쓰는 성분
);

-- ─────────────────────────────────────────────
-- 보관 조건 (product_storage.csv, 16행) — 상품 1 : 보관 N
-- ─────────────────────────────────────────────
create table public.product_storage (
  id           bigint generated by default as identity primary key,
  product_id   text not null references public.products (product_id) on delete cascade,
  stage        text not null check (stage in ('개봉 전', '개봉 후', '수령 후')),
  storage_type text check (storage_type in ('상온', '냉장', '냉동')),  -- NULL 2행 있음
  days         integer check (days >= 0),         -- 일 단위, 1개월 = 30일. NULL 1행 있음
  note         text                               -- 원문 표현
);

-- ─────────────────────────────────────────────
-- 주의사항 (product_cautions.csv, 16행) — 상품 1 : 주의사항 N
-- ─────────────────────────────────────────────
create table public.product_cautions (
  id         bigint generated by default as identity primary key,
  product_id text not null references public.products (product_id) on delete cascade,
  area       text not null check (area in ('보관', '조리', '도구', '섭취')),
  level      text not null check (level in ('금지', '주의', '권장')),
  content    text not null,
  reason     text                                 -- NULL 6행 있음
);

-- 외래키 컬럼은 Postgres가 자동으로 인덱스를 만들지 않으므로 직접 만든다 (상품별 조회용)
create index product_storage_product_id_idx  on public.product_storage  (product_id);
create index product_cautions_product_id_idx on public.product_cautions (product_id);

-- ─────────────────────────────────────────────
-- 배송정책 (shipping_policy.csv, 1행) — 모든 상품 공통
-- ─────────────────────────────────────────────
create table public.shipping_policy (
  id                smallint primary key default 1 check (id = 1),  -- 항상 1행만 허용
  free_shipping_min integer not null check (free_shipping_min >= 0),
  base_fee          integer not null check (base_fee >= 0),
  same_day_regions  text not null,                -- 쉼표 구분 (예: 수성구, 달서구)
  same_day_cutoff   time not null,
  fresh_ship_days   text not null                 -- 예: 월~목
);

-- ─────────────────────────────────────────────
-- RLS (행 수준 보안)
-- 켜기만 하고 정책이 없으면 아무도 읽을 수 없다.
-- 아래는 누구나 읽기만 가능하게 하는 정책. 쓰기는 대시보드(서비스 키)에서만 한다.
-- 앱에서 로그인한 사용자만 읽게 하려면 "to anon, authenticated"를 "to authenticated"로 바꾼다.
-- ─────────────────────────────────────────────
alter table public.products         enable row level security;
alter table public.product_storage  enable row level security;
alter table public.product_cautions enable row level security;
alter table public.shipping_policy  enable row level security;

create policy "products 읽기 허용"         on public.products         for select to anon, authenticated using (true);
create policy "product_storage 읽기 허용"  on public.product_storage  for select to anon, authenticated using (true);
create policy "product_cautions 읽기 허용" on public.product_cautions for select to anon, authenticated using (true);
create policy "shipping_policy 읽기 허용"  on public.shipping_policy  for select to anon, authenticated using (true);
